//! Making `src/components/` reachable without a mod file to maintain.

use super::*;
use crate::tree::Tree;

/// The `mod.rs` generated for `relative`, a directory below the root.
fn mod_rs_for(scan: &Scan, root: &Path, relative: &str) -> String {
    let dir = if relative.is_empty() {
        root.to_path_buf()
    } else {
        root.join(relative)
    };
    let wanted = normalize(&dir.join("mod.rs"));
    scan.modules
        .iter()
        .find(|(path, _)| *path == wanted)
        .map(|(_, contents)| contents.clone())
        .unwrap_or_else(|| {
            panic!(
                "no mod.rs for `{relative}`; generated {:?}",
                scan.modules.iter().map(|(p, _)| p).collect::<Vec<_>>()
            )
        })
}

#[test]
fn every_file_becomes_a_module() {
    let tree = Tree::new("components");
    tree.file("button.rs", "pub fn Button() {}")
        .file("user_card.rs", "pub fn UserCard() {}");

    let scan = scan(tree.path());
    let root = mod_rs_for(&scan, tree.path(), "");
    assert!(root.contains("pub mod button;"), "{root}");
    assert!(root.contains("pub mod user_card;"), "{root}");
}

/// One `mod.rs` per directory, and the parent declares the child.
#[test]
fn nested_directories_are_wired_through() {
    let tree = Tree::new("nested");
    tree.file("forms/input.rs", "pub fn Input() {}");

    let scan = scan(tree.path());
    assert!(mod_rs_for(&scan, tree.path(), "").contains("pub mod forms;"));
    assert!(mod_rs_for(&scan, tree.path(), "forms").contains("pub mod input;"));
}

/// The output is checked in, so the order must not depend on the filesystem.
#[test]
fn the_declarations_are_ordered() {
    let tree = Tree::new("order");
    tree.file("zebra.rs", "")
        .file("alpha.rs", "")
        .file("middle.rs", "");

    let root = mod_rs_for(&scan(tree.path()), tree.path(), "");
    let at = |name: &str| root.find(name).unwrap_or_else(|| panic!("{name} missing"));
    assert!(
        at("alpha") < at("middle") && at("middle") < at("zebra"),
        "{root}"
    );
}

#[test]
fn a_generated_mod_file_is_not_itself_a_module() {
    let tree = Tree::new("modrs");
    tree.file("button.rs", "").file("mod.rs", "// @generated");

    let root = mod_rs_for(&scan(tree.path()), tree.path(), "");
    assert!(!root.contains("pub mod mod;"), "{root}");
}

/// Editor droppings and `.git` are not modules.
#[test]
fn dotfiles_are_skipped() {
    let tree = Tree::new("dotfiles");
    tree.file("button.rs", "")
        .file(".hidden.rs", "")
        .dir(".git");

    let root = mod_rs_for(&scan(tree.path()), tree.path(), "");
    assert!(!root.contains("hidden"), "{root}");
    assert!(!root.contains("git"), "{root}");
}

#[test]
fn only_rust_files_are_declared() {
    let tree = Tree::new("notrust");
    tree.file("button.rs", "")
        .file("notes.md", "")
        .file("styles.css", "");

    let scan = scan(tree.path());
    let root = mod_rs_for(&scan, tree.path(), "");
    assert!(!root.contains("notes"), "{root}");
    assert!(!root.contains("styles"), "{root}");
    assert_eq!(scan.files.len(), 1);
}

/// `mod components;` is unconditional in `main.rs`, so a project that has not
/// written a component yet still has to compile.
#[test]
fn a_missing_directory_is_created_rather_than_reported() {
    let tree = Tree::new("create");
    let dir = tree.path().join("components");
    let scan = scan(&dir);

    assert!(dir.is_dir(), "the directory is created");
    assert!(scan.files.is_empty());
    let root = mod_rs_for(&scan, &dir, "");
    assert!(root.contains("No components yet"), "{root}");
}

/// Generated code is read by people too; a `mod.rs` says where it came from.
#[test]
fn the_output_says_it_is_generated() {
    let tree = Tree::new("header");
    tree.file("button.rs", "");

    let root = mod_rs_for(&scan(tree.path()), tree.path(), "");
    assert!(root.starts_with("// @generated by rahti-build"), "{root}");
    assert!(
        root.contains("dead_code"),
        "an unused component is one in progress"
    );
}

#[test]
fn the_directory_and_its_files_are_watched() {
    let tree = Tree::new("watch");
    tree.file("forms/input.rs", "");

    let scan = scan(tree.path());
    assert!(
        scan.watched.iter().any(|w| w.ends_with("/forms")),
        "{:?}",
        scan.watched
    );
    assert!(
        scan.watched.iter().any(|w| w.ends_with("/forms/input.rs")),
        "{:?}",
        scan.watched
    );
}

