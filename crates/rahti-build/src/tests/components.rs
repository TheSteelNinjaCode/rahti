/// The names are the app's, not one file's: the page hands any name it does
/// not have to the components, and two of them would leave nothing to pick
/// between.
#[test]
#[should_panic(expected = "two components declare an rpc named `like`")]
fn two_components_cannot_share_a_name() {
    let rpcs = vec![
        Rpc {
            name: "like".to_string(),
            module: "like_button".to_string(),
            file: "src/components/like_button.rs".to_string(),
        },
        Rpc {
            name: "like".to_string(),
            module: "star".to_string(),
            file: "src/components/star.rs".to_string(),
        },
    ];
    check_rpc_names(&rpcs, &[]);
}

/// The page answers its own names first, so a component sharing one would be
/// unreachable there and reachable everywhere else.
#[test]
#[should_panic(expected = "both as a page rpc and as a component rpc")]
fn a_component_cannot_take_a_name_a_page_has() {
    let rpcs = vec![Rpc {
        name: "like".to_string(),
        module: "like_button".to_string(),
        file: "src/components/like_button.rs".to_string(),
    }];
    check_rpc_names(&rpcs, &[page("src/app/widgets/page.rs", &["like"])]);
}

/// Two pages may each declare `save`, because a page answers on its own URL.
/// Only a clash with a component is a problem.
#[test]
fn two_pages_may_share_a_name() {
    check_rpc_names(
        &[],
        &[
            page("src/app/a/page.rs", &["save"]),
            page("src/app/b/page.rs", &["save"]),
        ],
    );
}
