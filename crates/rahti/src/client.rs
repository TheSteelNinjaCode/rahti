//! The page's client registry: every piece of client code `html!` compiled,
//! served as one same-origin module.
//!
//! The browser runtime never compiles page text — it runs only what this
//! module registers with `pp.registerClient`. That is what lets the default
//! Content-Security-Policy leave out `'unsafe-eval'`, and what keeps markup
//! injected into a page inert: a `{…}` no template wrote is not in the
//! registry, so the runtime renders it as text.
//!
//! `html!` submits one [`ClientCode`] per binding, handler and component
//! script it compiles; [`module`] gathers them on first use. The generated
//! router serves the module at [`PATH`], and `public/js/main.js` imports it
//! after the runtime and before `pp.mount()`.

use std::collections::BTreeMap;
use std::sync::OnceLock;

use axum::Router;
use axum::http::{HeaderMap, HeaderValue, StatusCode, header};
use axum::response::{IntoResponse, Response};
use axum::routing::get;

use crate::html::RenderJs;

#[cfg(test)]
#[path = "tests/client.rs"]
mod tests;

/// Where the generated router serves the client registry.
pub const PATH: &str = "/_rahti/client.js";

/// What a registry entry is, which decides the table it lands in.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum ClientKind {
    /// A `{…}` binding: `(scope) => value`.
    Expression,
    /// An `on…={…}` handler: `function (scope, event)`.
    Handler,
    /// A component `<script>`: `function (pp, __pp_server)`.
    Script,
}

/// One compiled piece of client code. Submitted by `html!`; not written by
/// hand.
#[derive(Debug)]
pub struct ClientCode {
    pub kind: ClientKind,
    /// The source as the runtime reads it back off the page, or a script's
    /// `pp-script` key.
    pub key: &'static str,
    /// The registry function, as JavaScript source.
    pub js: &'static str,
}

inventory::collect!(ClientCode);

/// The registry module and its validator.
#[derive(Debug)]
pub struct Module {
    pub source: String,
    pub etag: String,
}

/// The registry module for every [`ClientCode`] linked into this binary.
pub fn module() -> &'static Module {
    static MODULE: OnceLock<Module> = OnceLock::new();
    MODULE.get_or_init(|| build(inventory::iter::<ClientCode>()))
}

/// The compiled code of the component script registered under `key`.
pub fn script(key: &str) -> Option<&'static str> {
    inventory::iter::<ClientCode>()
        .find(|entry| entry.kind == ClientKind::Script && entry.key == key)
        .map(|entry| entry.js)
}

fn build<'a>(entries: impl IntoIterator<Item = &'a ClientCode>) -> Module {
    // Sorted and de-duplicated, so the module — and its ETag — depends only
    // on what was compiled, never on link order.
    let mut tables: BTreeMap<ClientKind, BTreeMap<&str, &str>> = BTreeMap::new();
    for entry in entries {
        tables
            .entry(entry.kind)
            .or_default()
            .entry(entry.key)
            .or_insert(entry.js);
    }

    let mut source = String::from(
        "// Generated by Rahti: this application's client code, compiled ahead of time.\n\
         // An identifier the code does not declare reads the scope, then the global object.\n\
         const __pp_read = (scope, name) => (name in scope ? scope[name] : globalThis[name]);\n\
         globalThis.pp.registerClient({\n",
    );
    for (kind, name) in [
        (ClientKind::Expression, "expressions"),
        (ClientKind::Handler, "handlers"),
        (ClientKind::Script, "scripts"),
    ] {
        source.push_str(&format!("  {name}: {{\n"));
        for (key, js) in tables.get(&kind).into_iter().flatten() {
            let key = serde_json::to_string(key).expect("a string always serializes");
            source.push_str(&format!("    {key}: {js},\n"));
        }
        source.push_str("  },\n");
    }
    source.push_str("});\n");

    let etag = format!("\"{:016x}\"", fnv1a64(&source));
    Module { source, etag }
}

/// The route serving [`module`] at [`PATH`].
pub fn routes() -> Router {
    Router::new().route(PATH, get(serve))
}

async fn serve(headers: HeaderMap) -> Response {
    let module = module();
    let etag = HeaderValue::from_str(&module.etag).expect("a hex ETag is a valid header");
    if headers
        .get(header::IF_NONE_MATCH)
        .is_some_and(|value| value == etag)
    {
        return (StatusCode::NOT_MODIFIED, [(header::ETAG, etag)]).into_response();
    }
    (
        [
            (
                header::CONTENT_TYPE,
                HeaderValue::from_static("text/javascript; charset=utf-8"),
            ),
            // Revalidated on every load, so a redeploy is picked up at once.
            (header::CACHE_CONTROL, HeaderValue::from_static("no-cache")),
            (header::ETAG, etag),
        ],
        module.source.clone(),
    )
        .into_response()
}

/// Write a component script's server values as its `pp-data` attribute: one
/// JSON array, in the order the script reads them as `__pp_server`.
pub fn write_script_data(values: &[&dyn RenderJs], out: &mut String) {
    let mut json = String::from("[");
    for (index, value) in values.iter().enumerate() {
        if index > 0 {
            json.push(',');
        }
        value.render_js_into(&mut json);
    }
    json.push(']');

    out.push_str(" pp-data=\"");
    for c in json.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '"' => out.push_str("&quot;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            c => out.push(c),
        }
    }
    out.push('"');
}

fn fnv1a64(input: &str) -> u64 {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in input.as_bytes() {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    hash
}
