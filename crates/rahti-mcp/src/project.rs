use std::{
    collections::BTreeSet,
    env, fs,
    path::{Path, PathBuf},
};

use serde_json::{Value, json};

const CONFIG_FILE: &str = "rahti.config.json";
const MANIFEST_FILE: &str = ".rahti/manifest.json";
const DIAGNOSTICS_FILE: &str = ".rahti/dev.log";
const CONVENTIONS_DIR: &str = "docs/conventions";
const MAX_DIAGNOSTICS: usize = 200;

#[derive(Debug, Clone)]
pub struct Project {
    root: PathBuf,
    transport: &'static str,
    expose_root: bool,
}

impl Project {
    pub fn open(root: impl AsRef<Path>) -> Result<Self, String> {
        let root = root.as_ref().canonicalize().map_err(|error| {
            format!(
                "cannot resolve project root {}: {error}",
                root.as_ref().display()
            )
        })?;
        if !root.join(CONFIG_FILE).is_file() {
            return Err(format!(
                "{} is not a Rahti project: {CONFIG_FILE} is missing",
                root.display()
            ));
        }
        Ok(Self {
            root,
            transport: "stdio-local",
            expose_root: true,
        })
    }

    #[cfg(feature = "http")]
    pub(crate) fn open_http(root: impl AsRef<Path>) -> Result<Self, String> {
        let mut project = Self::open(root)?;
        project.transport = "streamable-http";
        project.expose_root = false;
        Ok(project)
    }

    pub fn root(&self) -> &Path {
        &self.root
    }

    pub(crate) fn server_instructions(&self) -> String {
        format!(
            "Read-only Rahti project context over {}. This server never reads .env, never mutates the project, and does not act as a browser-authenticated application user.",
            self.transport
        )
    }

    pub fn config(&self) -> Result<Value, String> {
        let mut config = self.read_json(CONFIG_FILE)?;
        redact_secrets(&mut config);
        Ok(config)
    }

    pub fn manifest(&self) -> Result<Value, String> {
        self.read_json(MANIFEST_FILE)
    }

    pub fn summary(&self) -> Result<Value, String> {
        let config = self.config()?;
        let manifest = self.manifest()?;
        Ok(json!({
            "projectRoot": self.expose_root.then(|| self.root.display().to_string()),
            "createdWith": config.get("createdWith"),
            "appDir": manifest.get("appDir"),
            "webSocketsEnabled": config.get("ws").and_then(Value::as_bool).unwrap_or(false),
            "database": manifest.get("db"),
            "counts": {
                "routes": array(&manifest, "routes").len(),
                "layouts": array(&manifest, "layouts").len(),
                "components": array(&manifest, "components").len(),
                "sockets": array(&manifest, "sockets").len(),
                "pageRpcs": rpc_contracts(&manifest)?.iter().filter(|rpc| rpc["scope"] == "page").count(),
                "componentRpcs": rpc_contracts(&manifest)?.iter().filter(|rpc| rpc["scope"] == "component").count(),
            },
            "authentication": {
                "routePolicy": "runtime",
                "routePrivacyKnown": false,
                "rpcAndSocketRequirementsKnown": true,
                "mcpTransport": self.transport,
                "browserSessionUsed": false,
            }
        }))
    }

    pub fn routes(&self) -> Result<Value, String> {
        Ok(Value::Array(array(&self.manifest()?, "routes").to_vec()))
    }

    pub fn components(&self) -> Result<Value, String> {
        Ok(Value::Array(
            array(&self.manifest()?, "components").to_vec(),
        ))
    }

    pub fn rpcs(&self) -> Result<Value, String> {
        let manifest = self.manifest()?;
        Ok(Value::Array(rpc_contracts(&manifest)?.to_vec()))
    }

    pub fn sockets(&self) -> Result<Value, String> {
        Ok(Value::Array(array(&self.manifest()?, "sockets").to_vec()))
    }

    pub fn database_artifacts(&self) -> Result<Value, String> {
        Ok(self.manifest()?.get("db").cloned().unwrap_or(Value::Null))
    }

    pub fn site_info(&self) -> Result<Value, String> {
        let content = fs::read_to_string(self.site_info_path()?)
            .map_err(|error| format!("cannot read public site information: {error}"))?;
        Ok(json!({
            "source": "/llms.txt",
            "content": content,
        }))
    }

    pub fn has_site_info(&self) -> bool {
        self.site_info_path().is_ok_and(|path| path.is_file())
    }

    pub fn validate(&self) -> Result<Value, String> {
        let manifest = self.manifest()?;
        let mut errors = Vec::new();
        let mut warnings = vec![
            "Private route policy is installed at runtime and is not inferred from source."
                .to_string(),
        ];

        if manifest.get("generatedBy").and_then(Value::as_str) != Some("rahti-build") {
            errors.push(format!("{MANIFEST_FILE} was not generated by rahti-build"));
        }

        let mut files = BTreeSet::new();
        for section in [
            "routes",
            "layouts",
            "errors",
            "loading",
            "components",
            "sockets",
        ] {
            for item in array(&manifest, section) {
                if let Some(file) = item.get("file").and_then(Value::as_str) {
                    files.insert(file.to_string());
                }
            }
        }
        if let Some(db) = manifest.get("db") {
            for section in ["models", "migrations"] {
                for file in array(db, section).iter().filter_map(Value::as_str) {
                    files.insert(file.to_string());
                }
            }
        }
        for file in &files {
            if !self.root.join(file).is_file() {
                errors.push(format!("manifest file is missing: {file}"));
            }
        }
        if !self.root.join(DIAGNOSTICS_FILE).exists() {
            warnings.push(format!(
                "{DIAGNOSTICS_FILE} is absent; it is created during development"
            ));
        }

        Ok(json!({
            "valid": errors.is_empty(),
            "checkedFiles": files.len(),
            "errors": errors,
            "warnings": warnings,
        }))
    }

    pub fn recent_diagnostics(&self, requested_limit: Option<usize>) -> Result<Value, String> {
        let limit = requested_limit.unwrap_or(50).clamp(1, MAX_DIAGNOSTICS);
        let path = self.root.join(DIAGNOSTICS_FILE);
        if !path.exists() {
            return Ok(json!({ "limit": limit, "entries": [] }));
        }
        let text = fs::read_to_string(&path)
            .map_err(|error| format!("cannot read {}: {error}", path.display()))?;
        let lines = text
            .lines()
            .filter(|line| !line.trim().is_empty())
            .collect::<Vec<_>>();
        let entries = lines
            .iter()
            .skip(lines.len().saturating_sub(limit))
            .map(|line| serde_json::from_str(line).unwrap_or_else(|_| json!({ "raw": line })))
            .collect::<Vec<Value>>();
        Ok(json!({ "limit": limit, "entries": entries }))
    }

    pub fn convention_resources(&self) -> Result<Vec<(String, String, PathBuf)>, String> {
        let directory = self
            .root
            .join(CONVENTIONS_DIR)
            .canonicalize()
            .map_err(|error| format!("cannot resolve {CONVENTIONS_DIR}: {error}"))?;
        let entries = fs::read_dir(&directory)
            .map_err(|error| format!("cannot read {}: {error}", directory.display()))?;
        let mut resources = entries
            .filter_map(Result::ok)
            .filter_map(|entry| {
                let path = entry.path();
                if path.extension().and_then(|value| value.to_str()) != Some("md") {
                    return None;
                }
                let stem = path.file_stem()?.to_str()?.to_string();
                let canonical = path.canonicalize().ok()?;
                canonical
                    .starts_with(&directory)
                    .then(|| (format!("rahti://conventions/{stem}"), stem, canonical))
            })
            .collect::<Vec<_>>();
        resources.sort_by(|left, right| left.0.cmp(&right.0));
        Ok(resources)
    }

    pub fn read_resource(&self, uri: &str) -> Result<String, String> {
        match uri {
            "rahti://project/config" => pretty(self.config()?),
            "rahti://project/manifest" => pretty(self.manifest()?),
            "rahti://site/llms" => fs::read_to_string(self.site_info_path()?)
                .map_err(|error| format!("cannot read public site information: {error}")),
            _ => {
                let (_, _, path) = self
                    .convention_resources()?
                    .into_iter()
                    .find(|(candidate, _, _)| candidate == uri)
                    .ok_or_else(|| format!("unknown Rahti resource: {uri}"))?;
                fs::read_to_string(&path)
                    .map_err(|error| format!("cannot read {}: {error}", path.display()))
            }
        }
    }

    fn read_json(&self, relative: &str) -> Result<Value, String> {
        let path = self.root.join(relative);
        let text = fs::read_to_string(&path)
            .map_err(|error| format!("cannot read {}: {error}", path.display()))?;
        serde_json::from_str(&text)
            .map_err(|error| format!("invalid JSON in {}: {error}", path.display()))
    }

    fn site_info_path(&self) -> Result<PathBuf, String> {
        let configured = env::var("RAHTI_PUBLIC_DIR")
            .ok()
            .filter(|value| !value.trim().is_empty())
            .or_else(|| {
                self.config()
                    .ok()?
                    .pointer("/app/public")?
                    .as_str()
                    .map(str::to_string)
            })
            .unwrap_or_else(|| "public".to_string());
        let directory = PathBuf::from(configured);
        let directory = if directory.is_absolute() {
            directory
        } else {
            self.root.join(directory)
        };
        Ok(directory.join("llms.txt"))
    }
}

fn array<'a>(value: &'a Value, key: &str) -> &'a [Value] {
    value
        .get(key)
        .and_then(Value::as_array)
        .map(Vec::as_slice)
        .unwrap_or(&[])
}

fn rpc_contracts(manifest: &Value) -> Result<&Vec<Value>, String> {
    if manifest.get("rpcContractVersion").and_then(Value::as_u64) != Some(1) {
        return Err("rahti[RAHTI_RPC_CONTRACT_MANIFEST]: RPC contracts are missing or unsupported. Run cargo check to regenerate .rahti/manifest.json.".into());
    }
    manifest.get("rpcContracts").and_then(Value::as_array).ok_or_else(||
        "rahti[RAHTI_RPC_CONTRACT_MANIFEST]: rpcContracts must be an array. Run cargo check to regenerate .rahti/manifest.json.".into())
}

fn redact_secrets(value: &mut Value) {
    match value {
        Value::Object(object) => {
            for (key, value) in object {
                let normalized = key.to_ascii_lowercase().replace(['-', '_'], "");
                if [
                    "secret",
                    "token",
                    "password",
                    "credential",
                    "databaseurl",
                    "connectionstring",
                ]
                .iter()
                .any(|sensitive| normalized.contains(sensitive))
                {
                    *value = Value::String("[redacted]".to_string());
                } else {
                    redact_secrets(value);
                }
            }
        }
        Value::Array(values) => values.iter_mut().for_each(redact_secrets),
        _ => {}
    }
}

fn pretty(value: Value) -> Result<String, String> {
    serde_json::to_string_pretty(&value).map_err(|error| error.to_string())
}

#[cfg(test)]
pub(crate) struct TestProject {
    pub project: Project,
    root: PathBuf,
}

#[cfg(test)]
impl Drop for TestProject {
    fn drop(&mut self) {
        let temporary = env::temp_dir();
        if self.root.starts_with(&temporary)
            && self
                .root
                .file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| name.starts_with("rahti-mcp-test-"))
        {
            let _ = fs::remove_dir_all(&self.root);
        }
    }
}

#[cfg(test)]
pub(crate) fn test_project() -> TestProject {
    use std::sync::atomic::{AtomicU64, Ordering};

    static NEXT: AtomicU64 = AtomicU64::new(0);
    let root = env::temp_dir().join(format!(
        "rahti-mcp-test-{}-{}",
        std::process::id(),
        NEXT.fetch_add(1, Ordering::Relaxed)
    ));
    fs::create_dir_all(root.join(".rahti")).expect("create manifest directory");
    fs::create_dir_all(root.join("docs/conventions")).expect("create conventions directory");
    fs::write(
        root.join(CONFIG_FILE),
        r#"{"createdWith":"test","app":{"public":"public"}}"#,
    )
    .expect("write project config");
    fs::write(
        root.join(MANIFEST_FILE),
        r#"{
  "generatedBy": "rahti-build",
  "rpcContractVersion": 1,
  "rpcContracts": [{
    "name": "rename", "scope": "page", "authRequired": true,
    "file": "src/app/account/page.rs", "line": 10,
    "parameters": [{"name": "name", "rustType": "String"}],
    "response": {"schemaStatus": "unresolved"},
    "checks": {"dynamicValues": "server"}
  }],
  "appDir": "src/app",
  "routes": [{
    "url": "/account",
    "file": "src/app/account/page.rs",
    "rpcs": ["rename"],
    "authRpcs": ["rename"]
  }],
  "layouts": [],
  "errors": [],
  "loading": [],
  "components": [],
  "sockets": []
}"#,
    )
    .expect("write project manifest");
    fs::write(root.join("docs/conventions/testing.md"), "# Testing\n").expect("write convention");
    let project = Project::open(&root).expect("open test project");
    TestProject { project, root }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_project_exposes_authenticated_callables() {
        let fixture = test_project();
        let project = &fixture.project;
        let rpcs = project.rpcs().expect("RPC inventory");
        let rename = rpcs
            .as_array()
            .unwrap()
            .iter()
            .find(|rpc| rpc.get("name").and_then(Value::as_str) == Some("rename"))
            .expect("account rename RPC");
        assert_eq!(rename["authRequired"], true);
        assert!(rename["line"].as_u64().unwrap() > 0);
        let name = rename["parameters"]
            .as_array()
            .unwrap()
            .iter()
            .find(|parameter| parameter["name"] == "name")
            .unwrap();
        assert_eq!(name["rustType"], "String");
        assert_eq!(rename["response"]["schemaStatus"], "unresolved");
        assert_eq!(rename["checks"]["dynamicValues"], "server");
        assert_eq!(
            project.summary().unwrap()["authentication"]["browserSessionUsed"],
            false
        );
    }

    #[test]
    fn diagnostics_limit_is_bounded() {
        let fixture = test_project();
        let project = &fixture.project;
        assert_eq!(
            project.recent_diagnostics(Some(usize::MAX)).unwrap()["limit"],
            MAX_DIAGNOSTICS
        );
    }

    #[test]
    fn rpc_discovery_requires_the_generated_contract_inventory() {
        for manifest in [
            json!({}),
            json!({"rpcContractVersion": 2, "rpcContracts": []}),
            json!({"rpcContractVersion": 1}),
        ] {
            assert!(
                rpc_contracts(&manifest)
                    .unwrap_err()
                    .contains("RAHTI_RPC_CONTRACT_MANIFEST")
            );
        }
        assert!(
            rpc_contracts(&json!({"rpcContractVersion": 1, "rpcContracts": []}))
                .unwrap()
                .is_empty()
        );
    }
}
